#!/usr/bin/env python3
"""Embeds the WebGL textures, sound effects, asteroid mesh and font into web/.

Browsers refuse WebGL textures loaded from file:// URLs, so everything the 3D
scene needs is inlined as data URIs in web/js/assets.js. That keeps the game
playable by simply opening web/index.html. Only the standard library is used.
"""
import base64
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ASSETS = os.path.join(ROOT, 'assets')
WEB = os.path.join(ROOT, 'web')

MIME = {'.webp': 'image/webp', '.png': 'image/png', '.mp3': 'audio/mpeg', '.woff2': 'font/woff2'}


def data_uri(path):
    with open(path, 'rb') as f:
        payload = base64.b64encode(f.read()).decode('ascii')
    return 'data:%s;base64,%s' % (MIME[os.path.splitext(path)[1]], payload)


def embed_dir(name):
    folder = os.path.join(ASSETS, name)
    return {os.path.splitext(f)[0]: data_uri(os.path.join(folder, f)) for f in sorted(os.listdir(folder))}


def main():
    with open(os.path.join(ASSETS, 'asteroid_mesh.json')) as f:
        mesh = json.load(f)
    bundle = {'textures': embed_dir('textures'), 'sounds': embed_dir('sounds'), 'asteroidMesh': mesh}
    with open(os.path.join(WEB, 'js', 'assets.js'), 'w') as f:
        f.write('// Generated by tools/build_assets.py - do not edit.\nwindow.SE_ASSETS=')
        json.dump(bundle, f, separators=(',', ':'))
        f.write(';\n')

    font = data_uri(os.path.join(ASSETS, 'roboto-700.woff2'))
    with open(os.path.join(WEB, 'fonts.css'), 'w') as f:
        f.write("@font-face{font-family:'Roboto';font-weight:700;font-style:normal;"
                "font-display:swap;src:url(%s) format('woff2')}\n" % font)
    print('web/js/assets.js and web/fonts.css written')


if __name__ == '__main__':
    main()
